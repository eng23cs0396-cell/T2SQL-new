def populate_cases():
    formatted_cases = []
    for spec in COMPLEX_CASES_SPEC:
        db_path = os.path.join(DB_DIR, spec["db_file"])
        extractor = DatabaseSchemaExtractor(db_path)
        schema_data = extractor.extract_full_schema()
        schema_text = schema_data["formatted_text"]
        
        instruction = f"{schema_text}\n\nQuestion: {spec['question']}"
        formatted_cases.append({
            "id": spec["id"],
            "db_id": spec["db_id"],
            "instruction": instruction,
            "output": spec["query"],
            "question": spec["question"],
            "query": spec["query"],
            "schema_text": schema_text
        })

    # Read existing spider_test.json if available
    existing = []
    if os.path.exists(TEST_PATH):
        with open(TEST_PATH, "r", encoding="utf-8") as f:
            try:
                existing = json.load(f)
            except Exception:
                existing = []

    # Filter out any prior complex_ cases
    filtered = [c for c in existing if not str(c.get("id", "")).startswith("complex_")]

    # Prepend new complex cases so limit=15 or limit=24 will test all complex cases!
    final_cases = formatted_cases + filtered

    with open(TEST_PATH, "w", encoding="utf-8") as f:
        json.dump(final_cases, f, indent=2)

    print(f"[SUCCESS] Added {len(formatted_cases)} complex benchmark cases across 7 databases to {TEST_PATH}")
    print(f"Total test cases in dataset: {len(final_cases)}")


if __name__ == "__main__":
    populate_cases()
